"""Release hygiene checks for the publishable source tree."""

from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]

FORBIDDEN_DIRS = {"node_modules", "__pycache__", ".web-agent-swarm"}
SECRET_PATTERNS = [
    re.compile(r"sk-[A-Za-z0-9_-]{20,}"),
    re.compile(r"ghp_[A-Za-z0-9]{20,}"),
    re.compile(r"(?i)(api[_-]?key|access[_-]?token|password)\s*[:=]\s*[^<\s][^\s]{7,}"),
]
MACHINE_PATH_PATTERNS = [
    re.compile(r"[A-Za-z]:\\Users\\[^\\\s]+"),
    re.compile(r"/Users/[^/\s]+"),
    re.compile(r"/home/[^/\s]+"),
    re.compile(r"(?i)\\\\wsl(?:\.localhost|\$)?\\"),
    re.compile(r"(?i)wsl\.localhost"),
    re.compile(r"(?i)WSL_[A-Za-z0-9_.-]+"),
    re.compile(r"(?i)[A-Za-z0-9-]+\.(?:ts\.net|tailnet-[A-Za-z0-9.-]+)"),
]

issues = []

for path in ROOT.rglob("*"):
    if path.is_dir() and path.name in FORBIDDEN_DIRS:
        issues.append("generated directory present: {0}".format(path.relative_to(ROOT)))
        continue
    if not path.is_file():
        continue
    if path.suffix.lower() in {".pyc", ".pyo"}:
        issues.append("generated bytecode present: {0}".format(path.relative_to(ROOT)))
        continue
    try:
        text = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        continue

    for pattern in SECRET_PATTERNS:
        if pattern.search(text):
            issues.append("possible secret in {0}".format(path.relative_to(ROOT)))
    if path.resolve() != Path(__file__).resolve():
        for pattern in MACHINE_PATH_PATTERNS:
            if pattern.search(text):
                issues.append("machine-specific absolute path in {0}".format(path.relative_to(ROOT)))

if issues:
    print("Release check failed:")
    for issue in sorted(set(issues)):
        print("- " + issue)
    raise SystemExit(1)

print("Release check passed.")
